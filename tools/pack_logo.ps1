# Converts assets\lairlynx_logo.jpg (black logo on white) into an 8-bit coverage
# mask for the splash screen: source\splash_logo.c / .h. The game draws it in
# cream on black, so coverage 255 = fully lit.
$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Drawing

$root = Split-Path -Parent $PSScriptRoot
$source = [System.Drawing.Bitmap]::FromFile((Join-Path $root "assets\lairlynx_logo.jpg"))
$targetHeight = 104

# Bounding box of the dark pixels.
$minX = $source.Width; $minY = $source.Height; $maxX = 0; $maxY = 0
for ($y = 0; $y -lt $source.Height; $y += 2) {
    for ($x = 0; $x -lt $source.Width; $x += 2) {
        if ($source.GetPixel($x, $y).R -lt 128) {
            if ($x -lt $minX) { $minX = $x }; if ($x -gt $maxX) { $maxX = $x }
            if ($y -lt $minY) { $minY = $y }; if ($y -gt $maxY) { $maxY = $y }
        }
    }
}
$cropWidth = $maxX - $minX + 1
$cropHeight = $maxY - $minY + 1
$targetWidth = [int][Math]::Round($cropWidth * $targetHeight / $cropHeight)

$scaled = [System.Drawing.Bitmap]::new($targetWidth, $targetHeight)
$graphics = [System.Drawing.Graphics]::FromImage($scaled)
$graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
$graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
$graphics.Clear([System.Drawing.Color]::White)
$graphics.DrawImage($source, [System.Drawing.Rectangle]::new(0, 0, $targetWidth, $targetHeight),
    [System.Drawing.Rectangle]::new($minX, $minY, $cropWidth, $cropHeight), [System.Drawing.GraphicsUnit]::Pixel)
$graphics.Dispose()

$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('#include "splash_logo.h"')
[void]$builder.AppendLine()
[void]$builder.AppendLine("/* Generated by tools/pack_logo.ps1 from assets/lairlynx_logo.jpg. */")
[void]$builder.AppendLine("const u8 splashLogo[$($targetWidth * $targetHeight)] = {")
for ($y = 0; $y -lt $targetHeight; $y++) {
    $row = for ($x = 0; $x -lt $targetWidth; $x++) { "{0}" -f (255 - $scaled.GetPixel($x, $y).R) }
    [void]$builder.AppendLine("    " + ($row -join ",") + ",")
}
[void]$builder.AppendLine("};")
[System.IO.File]::WriteAllText((Join-Path $root "source\splash_logo.c"), $builder.ToString(), [System.Text.Encoding]::ASCII)

$header = @"
#ifndef STARDSI_SPLASH_LOGO_H
#define STARDSI_SPLASH_LOGO_H

#include <nds.h>

enum
{
    SPLASH_LOGO_WIDTH = $targetWidth,
    SPLASH_LOGO_HEIGHT = $targetHeight
};

// Coverage (0-255) of the lairLynx Studios logo, row by row.
extern const u8 splashLogo[SPLASH_LOGO_WIDTH * SPLASH_LOGO_HEIGHT];

#endif
"@
[System.IO.File]::WriteAllText((Join-Path $root "source\splash_logo.h"), $header, [System.Text.Encoding]::ASCII)
"Generated source/splash_logo.c and .h ($targetWidth x $targetHeight)."
